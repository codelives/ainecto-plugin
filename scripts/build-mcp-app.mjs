#!/usr/bin/env node
// Builds the AiNecto panel MCP App into one self-contained HTML file (KAN-369).
//   node scripts/build-mcp-app.mjs           write mcp-app/dist/ainecto-panel.html and its .sha256
//   node scripts/build-mcp-app.mjs --check   exit 1 if the committed files differ from a fresh build
//
// The panel's data rules live in plugins/ainecto-panel/hooks/inbox.js (the Claude Code pane's file); the
// build inlines that same file, so the two panes cannot drift. MCP App hosts load the HTML with no
// network (default CSP: no external scripts), so everything is inlined: each module becomes a function
// scope, its `export`s are returned and its `import { a } from './x.js'` reads them. No dependencies.
// The ainecto-api server serves a copy of the output (scripts/copy-mcp-app.mjs); the .sha256 file goes
// with it and both repositories test that the HTML still matches it.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const TEMPLATE = 'mcp-app/panel.html';
/** Modules in load order: each may import only from modules above it. */
export const MODULES = ['plugins/ainecto-panel/hooks/inbox.js', 'mcp-app/bridge.js', 'mcp-app/panel.js'];
export const OUT_HTML = 'mcp-app/dist/ainecto-panel.html';
export const OUT_SHA = 'mcp-app/dist/ainecto-panel.html.sha256';
const SLOT = '/*@@BUNDLE@@*/';

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm;
const EXPORT_RE = /^export\s+(?:async\s+)?(?:const|let|function|class)\s+([A-Za-z_$][\w$]*)/gm;

const varName = (rel) => '__' + rel.replace(/[^A-Za-z0-9]/g, '_');

/** Pure: module sources → one script. Throws on an import it cannot resolve. */
export function bundle(sources) {
  const known = new Map(); // rel path -> exported names
  const parts = [];
  for (const [rel, source] of sources) {
    const exported = [...source.matchAll(EXPORT_RE)].map((m) => m[1]);
    let body = source.replace(IMPORT_RE, (_, names, from) => {
      const target = join(dirname(rel), from).replace(/\\/g, '/');
      const exports = known.get(target);
      if (!exports) throw new Error(`${rel}: imports ${from} (${target}), which is not an earlier module`);
      const wanted = names.split(',').map((n) => n.trim()).filter(Boolean);
      const missing = wanted.filter((n) => !exports.includes(n));
      if (missing.length) throw new Error(`${rel}: ${target} does not export ${missing.join(', ')}`);
      return `const { ${wanted.join(', ')} } = ${varName(target)};`;
    });
    if (/^\s*(import|export)\b/m.test(body.replace(EXPORT_RE, ''))) {
      throw new Error(`${rel}: an import or export form the build does not handle`);
    }
    body = body.replace(/^export\s+/gm, '');
    if (body.includes('</script')) throw new Error(`${rel}: contains </script, which would end the inline script`);
    known.set(rel, exported);
    parts.push(`// ── ${rel} ──\nconst ${varName(rel)} = (() => {\n${body}\nreturn { ${exported.join(', ')} };\n})();`);
  }
  return `'use strict';\n${parts.join('\n\n')}\n`;
}

/** Reads the sources and returns { html, sha256 }. */
export function build(root = ROOT) {
  const template = readFileSync(join(root, TEMPLATE), 'utf8');
  if (!template.includes(SLOT)) throw new Error(`${TEMPLATE} has no ${SLOT}`);
  const sources = MODULES.map((rel) => [rel, readFileSync(join(root, rel), 'utf8')]);
  const banner =
    `<!-- AiNecto panel MCP App. Generated by ainecto-plugin scripts/build-mcp-app.mjs from ${TEMPLATE}, ` +
    `${MODULES.join(', ')}. Do not edit: change the sources and rebuild. -->\n`;
  const html = banner + template.replace(SLOT, () => bundle(sources));
  return { html, sha256: sha256Line(html) };
}

/** The .sha256 file content (the `sha256sum` format). */
export function sha256Line(html) {
  return `${createHash('sha256').update(html, 'utf8').digest('hex')}  ainecto-panel.html\n`;
}

/** Paths whose committed content differs from a fresh build. */
export function diffAgainstDisk(root = ROOT) {
  const { html, sha256 } = build(root);
  const stale = [];
  for (const [rel, want] of [[OUT_HTML, html], [OUT_SHA, sha256]]) {
    const path = join(root, rel);
    if (!existsSync(path) || readFileSync(path, 'utf8') !== want) stale.push(rel);
  }
  return stale;
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = diffAgainstDisk();
    if (stale.length) {
      console.error(`stale: ${stale.join(', ')} — run npm run build:app`);
      process.exit(1);
    }
    console.log('mcp-app: up to date');
  } else {
    const { html, sha256 } = build();
    mkdirSync(join(ROOT, dirname(OUT_HTML)), { recursive: true });
    writeFileSync(join(ROOT, OUT_HTML), html);
    writeFileSync(join(ROOT, OUT_SHA), sha256);
    console.log(`wrote ${relative(process.cwd(), join(ROOT, OUT_HTML))} (${html.length} chars) sha256 ${sha256.split(' ')[0]}`);
  }
}
